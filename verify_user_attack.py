#!/usr/bin/env python3
"""
Recover an AES-128 key from output.csv generated by aes_timing.cpp.

The CSV must contain ciphertext_hex plus 16 probe timing columns named
line0,line1,...,line15. These columns model the measured latency of probing
the 16 logical cache lines of a byte-oriented final-round S-box.
"""

from __future__ import annotations

import argparse
import csv
from dataclasses import dataclass
from pathlib import Path


SBOX = bytes.fromhex(
    "637c777bf26b6fc53001672bfed7ab76"
    "ca82c97dfa5947f0add4a2af9ca472c0"
    "b7fd9326363ff7cc34a5e5f171d83115"
    "04c723c31896059a071280e2eb27b275"
    "09832c1a1b6e5aa0523bd6b329e32f84"
    "53d100ed20fcb15b6acbbe394a4c58cf"
    "d0efaafb434d338545f9027f503c9fa8"
    "51a3408f929d38f5bcb6da2110fff3d2"
    "cd0c13ec5f974417c4a77e3d645d1973"
    "60814fdc222a908846eeb814de5e0bdb"
    "e0323a0a4906245cc2d3ac629195e479"
    "e7c8376d8dd54ea96c56f4ea657aae08"
    "ba78252e1ca6b4c6e8dd741f4bbd8b8a"
    "703eb5664803f60e613557b986c11d9e"
    "e1f8981169d98e949b1e87e9ce5528df"
    "8ca1890dbfe6426841992d0fb054bb16"
)

INV_SBOX = bytearray(256)
for _i, _value in enumerate(SBOX):
    INV_SBOX[_value] = _i
INV_SBOX = bytes(INV_SBOX)

RCON = (0x00, 0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1B, 0x36)
PROBE_COLUMNS = tuple(f"line{i}" for i in range(16))


@dataclass(frozen=True)
class Trace:
    ciphertext: bytes
    probe_times: tuple[float, ...]


def xor_word(a: bytes, b: bytes) -> bytes:
    return bytes(x ^ y for x, y in zip(a, b))


def schedule_core(word: bytes, round_number: int) -> bytes:
    rotated = word[1:] + word[:1]
    substituted = bytes(SBOX[x] for x in rotated)
    return bytes((substituted[0] ^ RCON[round_number], *substituted[1:]))


def expand_aes128_key(master_key: bytes) -> list[bytes]:
    if len(master_key) != 16:
        raise ValueError("AES-128 requires a 16-byte key")

    words = [master_key[i : i + 4] for i in range(0, 16, 4)]
    for i in range(4, 44):
        temp = words[i - 1]
        if i % 4 == 0:
            temp = schedule_core(temp, i // 4)
        words.append(xor_word(words[i - 4], temp))

    return [b"".join(words[i : i + 4]) for i in range(0, 44, 4)]


def reverse_aes128_schedule(round10_key: bytes) -> bytes:
    if len(round10_key) != 16:
        raise ValueError("round key must contain 16 bytes")

    words: list[bytes | None] = [None] * 44
    for j in range(4):
        words[40 + j] = round10_key[4 * j : 4 * j + 4]

    for i in range(43, 3, -1):
        current = words[i]
        previous = words[i - 1]
        assert current is not None and previous is not None
        if i % 4 == 0:
            temp = schedule_core(previous, i // 4)
        else:
            temp = previous
        words[i - 4] = xor_word(current, temp)

    return b"".join(word for word in words[:4] if word is not None)


def load_traces_from_csv(path: Path) -> list[Trace]:
    traces: list[Trace] = []
    with path.open(newline="") as fp:
        reader = csv.DictReader(fp)
        if reader.fieldnames is None:
            raise ValueError(f"{path} is empty")

        required = {"ciphertext_hex", *PROBE_COLUMNS}
        missing = sorted(required - set(reader.fieldnames))
        if missing:
            raise ValueError(f"{path} misses required columns: {', '.join(missing)}")

        for row_number, row in enumerate(reader, start=2):
            try:
                ciphertext = bytes.fromhex(row["ciphertext_hex"])
                if len(ciphertext) != 16:
                    raise ValueError("ciphertext is not one AES block")
                probe_times = tuple(float(row[column]) for column in PROBE_COLUMNS)
            except Exception as exc:
                raise ValueError(f"bad CSV row {row_number}: {exc}") from exc
            traces.append(Trace(ciphertext, probe_times))

    if not traces:
        raise ValueError(f"{path} contains no traces")
    return traces


def recover_round10_key(traces: list[Trace], verbose: bool = True) -> bytes:
    recovered = bytearray()
    for position in range(16):
        candidates: list[tuple[float, int]] = []
        for candidate in range(256):
            total = 0.0
            for trace in traces:
                predicted_line = INV_SBOX[
                    trace.ciphertext[position] ^ candidate
                ] >> 4
                total += trace.probe_times[predicted_line]
            candidates.append((total / len(traces), candidate))

        candidates.sort()
        best_score, best_byte = candidates[0]
        recovered.append(best_byte)
        if verbose:
            runner_up_score, runner_up = candidates[1]
            margin = runner_up_score - best_score
            print(
                f"RK10[{position:02d}] = {best_byte:02x}  "
                f"mean={best_score:7.2f}, runner-up={runner_up:02x} "
                f"({runner_up_score:7.2f}), margin={margin:6.2f}"
            )

    return bytes(recovered)


def read_hex_key(path: Path) -> bytes:
    data = path.read_text().strip()
    key = bytes.fromhex(data)
    if len(key) != 16:
        raise ValueError(f"{path} does not contain a 16-byte AES-128 key")
    return key


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Recover AES-128 key from aes_timing.cpp output.csv"
    )
    parser.add_argument(
        "--csv",
        type=Path,
        default=Path("output.csv"),
        help="CSV trace file generated by aes_timing.cpp, default output.csv",
    )
    parser.add_argument(
        "--key-file",
        type=Path,
        help="optional key file generated by --write-key, used only to verify",
    )
    parser.add_argument(
        "--expected-key-hex",
        help="optional expected AES-128 key hex, used only to verify",
    )
    parser.add_argument(
        "--quiet",
        action="store_true",
        help="hide per-byte candidate scores",
    )
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    traces = load_traces_from_csv(args.csv)

    print(f"Loaded {len(traces)} traces from {args.csv}")
    recovered_round10 = recover_round10_key(traces, verbose=not args.quiet)
    recovered_master = reverse_aes128_schedule(recovered_round10)

    print(f"\nRecovered RK10 : {recovered_round10.hex()}")
    print(f"Recovered key  : {recovered_master.hex()}")

    expected_key = None
    if args.key_file is not None:
        expected_key = read_hex_key(args.key_file)
    if args.expected_key_hex is not None:
        expected_key = bytes.fromhex(args.expected_key_hex)
        if len(expected_key) != 16:
            raise ValueError("--expected-key-hex must be 32 hex characters")

    if expected_key is not None:
        expected_round10 = expand_aes128_key(expected_key)[10]
        print(f"Expected  RK10 : {expected_round10.hex()}")
        print(f"Expected key   : {expected_key.hex()}")
        if recovered_master != expected_key:
            raise SystemExit("attack failed; collect more traces")
        print("SUCCESS: AES-128 key recovered from output.csv")


if __name__ == "__main__":
    main()
